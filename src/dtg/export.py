"""Exports: URDF, comms map (IO channel -> joint), JSON report.

URDF conventions
* model frame = root link frame at the reference (scan) pose, metres;
* every non-root link frame sits on its parent joint's pivot with the model
  frame's orientation, so joint origins are pure translations (rpy 0) and
  axes are written in model coordinates; joint zero = the reference pose;
* joint limits = terminal ranges from the ROM step (Set ROM 1 / ROM 2);
* effort / velocity come from the servo library when a servo model is
  assigned, otherwise placeholders, labelled as such in the report.

Not generated yet (stubs): inertial blocks, MJCF, ros2_control, firmware
header. See TODOs below.
"""
from __future__ import annotations

import json
import xml.etree.ElementTree as ET
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

from . import __version__
from .kinematics import KinematicModel

PLACEHOLDER_EFFORT_NM = 1.0
PLACEHOLDER_VELOCITY_RAD_S = 5.0


@dataclass
class LinkGeometry:
    """Geometry of one link in the MODEL frame (metres) with provenance per part."""
    link: str
    parts: list = field(default_factory=list)  # [(trimesh.Trimesh, provenance, note)]


def link_frames(model: KinematicModel) -> dict[str, np.ndarray]:
    origins = {model.root: np.zeros(3)}
    for j in model.joints:
        origins[j.child] = np.asarray(j.pivot_model, float)
    return origins


def _fmt(values) -> str:
    return " ".join(f"{float(v):.9g}" for v in values)


def build_urdf(model: KinematicModel, name: str = "robot", mesh_files: dict | None = None,
               servo_specs: dict | None = None) -> ET.Element:
    mesh_files = mesh_files or {}
    servo_specs = servo_specs or {}
    origins = link_frames(model)
    robot = ET.Element("robot", name=name)
    robot.append(ET.Comment(f" generated by digital-twin-generator {__version__}; model frame = root link at the "
                            "reference (scan) pose; joint zero = reference pose "))
    linked = {model.root} | {j.child for j in model.joints} | {j.parent for j in model.joints}
    for link in sorted(linked, key=lambda l: (l != model.root, l)):
        node = ET.SubElement(robot, "link", name=link)
        node.append(ET.Comment(" TODO inertial: mass/CoM/inertia from materials + servo library (not measured yet) "))
        for filename in mesh_files.get(link, []):
            for tag in ("visual", "collision"):
                el = ET.SubElement(node, tag)
                ET.SubElement(el, "origin", xyz="0 0 0", rpy="0 0 0")
                geo = ET.SubElement(el, "geometry")
                ET.SubElement(geo, "mesh", filename=filename, scale="1 1 1")
    for j in model.joints:
        node = ET.SubElement(robot, "joint", name=j.name, type=j.type)
        ET.SubElement(node, "parent", link=j.parent)
        ET.SubElement(node, "child", link=j.child)
        ET.SubElement(node, "origin", xyz=_fmt(origins[j.child] - origins.get(j.parent, np.zeros(3))), rpy="0 0 0")
        ET.SubElement(node, "axis", xyz=_fmt(j.axis_model))
        spec = servo_specs.get(j.name)
        effort = spec["effort_nm"] if spec and spec.get("effort_nm") else PLACEHOLDER_EFFORT_NM
        velocity = spec["velocity_rad_s"] if spec and spec.get("velocity_rad_s") else PLACEHOLDER_VELOCITY_RAD_S
        ET.SubElement(node, "limit", lower=f"{j.lower:.9g}", upper=f"{j.upper:.9g}",
                      effort=f"{effort:.6g}", velocity=f"{velocity:.6g}")
    ET.indent(robot)
    return robot


def validate_urdf(path: str | Path) -> dict:
    """Structural checks we can do without ROS: one tree, known links,
    unit axes, lower < upper, referenced meshes exist. Uses yourdfpy as an
    independent loader when installed."""
    path = Path(path)
    root = ET.parse(path).getroot()
    if root.tag != "robot":
        raise ValueError("root element must be <robot>")
    links = [l.get("name") for l in root.findall("link")]
    if len(links) != len(set(links)) or not links:
        raise ValueError("link names must be unique and non-empty")
    parents, problems = {}, []
    for j in root.findall("joint"):
        p, c = j.find("parent").get("link"), j.find("child").get("link")
        if p not in links or c not in links:
            problems.append(f"{j.get('name')}: unknown link")
        if c in parents:
            problems.append(f"{c} has two parents")
        parents[c] = p
        if j.get("type") in ("revolute", "prismatic"):
            axis = np.array([float(x) for x in j.find("axis").get("xyz").split()])
            if not np.isclose(np.linalg.norm(axis), 1.0, atol=1e-6):
                problems.append(f"{j.get('name')}: axis not unit length")
            lim = j.find("limit")
            if lim is None or float(lim.get("lower")) >= float(lim.get("upper")):
                problems.append(f"{j.get('name')}: needs lower < upper")
    roots = [l for l in links if l not in parents]
    if len(roots) != 1:
        problems.append(f"expected one root link, found {roots}")
    for l in links:
        seen, node = set(), l
        while node in parents:
            if node in seen:
                problems.append("joint graph has a cycle")
                break
            seen.add(node)
            node = parents[node]
    for mesh in root.iter("mesh"):
        if not (path.parent / mesh.get("filename")).is_file():
            problems.append(f"missing mesh {mesh.get('filename')}")
    if problems:
        raise ValueError("; ".join(problems))
    result = {"links": len(links), "joints": len(parents), "root": roots[0], "independent_loader": None}
    try:
        from yourdfpy import URDF
        loaded = URDF.load(str(path), load_meshes=False, build_scene_graph=True)
        result["independent_loader"] = "yourdfpy"
        result["actuated_joints"] = list(loaded.actuated_joint_names)
    except ImportError:
        pass
    return result


def comms_map(model: KinematicModel, servo_models: dict | None = None) -> dict:
    """IO channel -> joint map for control code and firmware."""
    servo_models = servo_models or {}
    by_channel = {j.channel: j for j in model.joints}
    rows = []
    for ch in model.channels:
        row = {"channel": ch["channel"], "status": ch["status"], "joint": ch.get("joint"),
               "parent": ch.get("parent"), "child": ch.get("child"), "notes": ch.get("reasons", [])}
        j = by_channel.get(ch["channel"])
        if j:
            rom = sorted([j.terminal_range_1.pulse_us, j.terminal_range_2.pulse_us])
            row.update({
                "type": j.type, "direction": j.direction, "zero_pulse_us": round(j.zero_pulse_us, 1),
                "rad_per_us": j.rad_per_us, "us_per_rad": 1.0 / j.rad_per_us if j.rad_per_us else None,
                "rom_1_us": j.terminal_range_1.pulse_us, "rom_2_us": j.terminal_range_2.pulse_us,
                "safe_range_us": rom, "limits": [j.lower, j.upper],
                "limits_units": "rad" if j.type == "revolute" else "m",
                "servo_model": servo_models.get(j.name), "confidence": j.status,
                "provenance": "camera-measured (wiggle + ROM)"})
        rows.append(row)
    return {"schema": "dtg.comms-map/1", "generated": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            "convention": "angle = direction * (pulse_us - zero_pulse_us) * rad_per_us about the joint axis; "
                          "never command outside safe_range_us",
            "channels": rows}


def export_all(model: KinematicModel, out: str | Path, *, name: str = "robot",
               geometry: dict[str, LinkGeometry] | None = None, servo_models: dict | None = None,
               servo_specs: dict | None = None, health: dict | None = None, extra: dict | None = None) -> dict:
    """Write robot.urdf, meshes/, comms_map.json and report.json into `out`."""
    out = Path(out)
    (out / "meshes").mkdir(parents=True, exist_ok=True)
    origins = link_frames(model)
    mesh_files: dict[str, list[str]] = {}
    provenance: dict[str, list] = {}
    for link, geo in (geometry or {}).items():
        for n, (mesh, prov, note) in enumerate(geo.parts):
            local = mesh.copy()
            local.apply_translation(-origins.get(link, np.zeros(3)))
            fname = f"meshes/{link}_{n}_{prov}.stl"
            local.export(str(out / fname))
            mesh_files.setdefault(link, []).append(fname)
            provenance.setdefault(link, []).append({"file": fname, "provenance": prov, "note": note,
                                                    "faces": int(len(mesh.faces))})
    robot = build_urdf(model, name, mesh_files, servo_specs)
    urdf_path = out / "robot.urdf"
    ET.ElementTree(robot).write(urdf_path, encoding="utf-8", xml_declaration=True)
    validation = validate_urdf(urdf_path)
    cmap = comms_map(model, servo_models)
    (out / "comms_map.json").write_text(json.dumps(cmap, indent=2) + "\n")
    joints = []
    for j in model.joints:
        spec = (servo_specs or {}).get(j.name)
        joints.append({"name": j.name, "channel": j.channel, "status": j.status, "reasons": j.reasons,
                       "quality": j.quality, "limits": [j.lower, j.upper],
                       "terminal_range_1": {"pulse_us": j.terminal_range_1.pulse_us, "position": j.terminal_range_1.position},
                       "terminal_range_2": {"pulse_us": j.terminal_range_2.pulse_us, "position": j.terminal_range_2.position},
                       "effort_velocity": "servo library" if spec else "PLACEHOLDER (assign a servo model)"})
    report = {
        "schema": "dtg.report/1", "generator": f"digital-twin-generator {__version__}",
        "generated": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "verified": False,
        "verified_note": "Software output only. Nothing here is verified against the physical robot until "
                         "a sim-vs-real check passes; flagged joints need operator confirmation.",
        "urdf": {"path": "robot.urdf", **validation},
        "joints": joints, "flags": model.flags,
        "links": {l: {"tags": model.link_tags.get(l, []), "parts": provenance.get(l, [])}
                  for l in sorted(set(model.link_tags) | set(provenance))},
        "not_generated": ["inertial (mass/CoM/inertia)", "MJCF", "ros2_control", "firmware header"],
        "health": health, **(extra or {})}
    (out / "report.json").write_text(json.dumps(report, indent=2, default=_json_default) + "\n")
    return report


def _json_default(o):
    if isinstance(o, np.ndarray):
        return o.tolist()
    if isinstance(o, (np.floating, np.integer)):
        return o.item()
    if isinstance(o, np.bool_):
        return bool(o)
    raise TypeError(type(o))


